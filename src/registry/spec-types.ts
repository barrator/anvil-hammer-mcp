/** Manuscript sub-elements: same shape, little documented. */
function manuscriptChild(
  name: string,
  description: string,
  t: Pick<TypeDef, "list" | "parents"> & { fields: Record<string, FieldDef> },
): TypeDef {
  return worldType({
    name,
    description,
    path: name,
    granularities: ["0"],
    list: t.list,
    parents: t.parents,
    fields: {
      id: ro("string"),
      title: spec("string"),
      updateDate: ro("date"),
      ...t.fields,
    },
    quirks: ["The spec documents very few fields and no granularity for manuscript parts."],
  });
}
