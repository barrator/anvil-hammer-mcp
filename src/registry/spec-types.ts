/**
 * Element types added in stage E from the official OpenAPI spec (Boromir).
 * Everything here is `unverified` until a live-test run observes it; routes
 * come from the spec, except where a quirk says the live API differs.
 *
 * Text fields are marked BBCode only where World Anvil's editor uses BBCode
 * for them; the coverage probe reports whether real values hold BBCode tags.
 */
import { COMMON, bb, notes, parent, ref, refs, ro, spec, worldRef } from "./build.js";
import type { FieldDef, TypeDef } from "./types.js";

const G3 = ["-1", "0", "2"];
const G4 = ["-1", "0", "1", "2"];
const ALL = ["get", "list", "create", "update", "delete"] as const;

const author = () => ref("user", { writable: false });
const world = () => ref("world");
const image = (extra: Partial<FieldDef> = {}) =>
  ref("image", { note: "Reference to an image already uploaded on World Anvil.", ...extra });
const assumedBb = () =>
  bb({ note: "BBCode assumed from the editor; the spec only says text.", kindConfirmed: false });

/** A world-scoped type: listed under a parent, resolved to its world by `world` or a parent chain. */
function worldType(
  t: Omit<TypeDef, "verbs" | "granularities" | "defaultGranularity" | "backupGranularity"> &
    Partial<Pick<TypeDef, "verbs" | "granularities" | "defaultGranularity" | "backupGranularity">>,
): TypeDef {
  const granularities = t.granularities ?? G3;
  return {
    verbs: [...ALL],
    defaultGranularity: "0",
    backupGranularity: granularities.at(-1) ?? "0",
    ...t,
    granularities,
  };
}

