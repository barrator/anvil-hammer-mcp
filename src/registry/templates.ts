/**
 * Article template fields. The four probed templates list exactly the field
 * names the template probe saw in real granularity-2 responses (stage B probe,
 * 2026-11-28). Their status becomes `verified` through observed.ts; their
 * kind is inferred from the name and the spec (`kindConfirmed: false`) unless
 * observed.ts confirms it from a real value.
 */
import type { FieldDef, TemplateDef } from "./types.js";

const base = (extra: Partial<FieldDef>): FieldDef => ({
  kind: "string",
  status: "unverified",
  source: "probe",
  kindConfirmed: false,
  ...extra,
});

/** Long text, stored as BBCode. */
const text = () => base({ kind: "string", bbcode: true });
/** Short plain value (name, number written as text, date written as text). */
const short = (note?: string) => base({ kind: "string", ...(note ? { note } : {}) });
const int = () => base({ kind: "integer" });
const bool = () => base({ kind: "boolean" });
/** Link to another article, sent as {"id": ...}. */
const link = (note?: string) =>
  base({ kind: "ref", refType: "article", ...(note ? { note } : {}) });
/** List of links to articles. */
const links = () => base({ kind: "refs", refType: "article" });
/** Reference to an image already uploaded on World Anvil (no upload through the API). */
const image = () =>
  base({
    kind: "ref",
    refType: "image",
    note: "Image reference only; uploading is not possible through the API.",
  });
/** World Anvil internal ID (no world, no listing route). */
const internal = (note: string) => base({ kind: "ref", refType: "internal", note });

